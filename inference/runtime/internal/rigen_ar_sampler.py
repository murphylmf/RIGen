def reference_for_block(
    row: dict[str, Any],
    block_index: int,
    encoded_references: dict[int, Tensor],
    null_reference: Tensor,
) -> tuple[Tensor, bool, dict[str, Any]]:
    state = row["active_ref_schedule"][block_index]
    if not isinstance(state, dict):
        raise ValueError(f"Block {block_index} active_ref_schedule is not an object")
    ref_index = int(state.get("ref_bank_index", -1))
    present = bool(state.get("valid", False)) and ref_index >= 0
    if not present:
        return (
            null_reference,
            False,
            {
                "block": block_index,
                "present": False,
                "ref_bank_index": -1,
                "actor_id": None,
                "image_path": None,
            },
        )
    bank_entry = row["reference_bank"][ref_index]
    return (
        encoded_references[ref_index],
        True,
        {
            "block": block_index,
            "present": True,
            "ref_bank_index": ref_index,
            "actor_id": bank_entry.get("actor_id"),
            "appearance_id": bank_entry.get("appearance_id"),
            "image_path": bank_entry.get("default_image_path"),
        },
    )


def build_window_batch(
    *,
    strategy: ARSlidingRefStrategy,
    world_video_tokens: Tensor,
    world_video_shape: VideoLatentShape,
    reference_latents: Tensor,
    reference_present: bool,
    audio_tokens: Tensor,
    audio_shape: AudioLatentShape,
    joystick: Tensor,
    buttons: Tensor,
    prompt_schedule: dict[str, Tensor],
    fps: float,
    inference_history_chunks: int | None = None,
) -> dict[str, Any]:
    if strategy.config.name == "ar_teacher":
        from rigen_ar_model import build_strategy_batch
        return build_strategy_batch(
            strategy=strategy, video_tokens=world_video_tokens, audio_tokens=audio_tokens,
            video_shape=world_video_shape, audio_shape=audio_shape, fps=fps,
            action_joystick=joystick, action_buttons=buttons, prompt_schedule=prompt_schedule,
        )
    video_latents = strategy._video_patchifier.unpatchify(
        world_video_tokens, output_shape=world_video_shape
    )
    audio_latents = strategy._audio_patchifier.unpatchify(
        audio_tokens, output_shape=audio_shape
    )
    batch: dict[str, Any] = {
        "video_latents": video_latents,
        "reference_video_latents": reference_latents,
        "reference_present": torch.tensor(
            [reference_present], device=world_video_tokens.device, dtype=torch.bool
        ),
        "audio_latents": audio_latents,
        "fps": torch.tensor(
            [fps], device=world_video_tokens.device, dtype=torch.float32
        ),
        "has_audio": torch.ones(1, device=world_video_tokens.device, dtype=torch.bool),
        "audio_loss_eligible": torch.ones(
            1, device=world_video_tokens.device, dtype=torch.bool
        ),
        "action_joystick": joystick.unsqueeze(0).to(world_video_tokens.device),
        "action_buttons": buttons.unsqueeze(0).to(world_video_tokens.device),
    }
    batch.update(
        {
            key: value.to(world_video_tokens.device)
            for key, value in prompt_schedule.items()
        }
    )
    if inference_history_chunks is not None:
        batch["_sliding_ref_inference_history_chunks"] = int(
            inference_history_chunks
        )
    return batch


def inject_target(
    inputs: ModelInputs, *, current_video: Tensor, current_audio: Tensor
) -> ModelInputs:
    if (
        inputs.ar_video_block_token_ranges is None
        or inputs.ar_audio_block_token_ranges is None
    ):
        raise ValueError("Sliding-ref block ranges are missing")
    if inputs.audio is None:
        raise ValueError("Sliding-ref audio modality is missing")
    video_start, video_end = inputs.ar_video_block_token_ranges[-1]
    audio_start, audio_end = inputs.ar_audio_block_token_ranges[-1]
    video_latent = inputs.video.latent.clone()
    audio_latent = inputs.audio.latent.clone()
    video_latent[:, video_start:video_end] = current_video
    audio_latent[:, audio_start:audio_end] = current_audio
    return replace(
        inputs,
        video=replace(inputs.video, latent=video_latent),
        audio=replace(inputs.audio, latent=audio_latent),
    )


def target_x0(
    inputs: ModelInputs, video_pred: Tensor, audio_pred: Tensor | None
) -> tuple[Tensor, Tensor]:
    if (
        inputs.ar_video_block_token_ranges is None
        or inputs.ar_audio_block_token_ranges is None
    ):
        raise ValueError("Sliding-ref block ranges are missing")
    if inputs.audio is None or audio_pred is None:
        raise RuntimeError("Sliding-ref TI2AV inference requires audio output")
    video_start, video_end = inputs.ar_video_block_token_ranges[-1]
    audio_start, audio_end = inputs.ar_audio_block_token_ranges[-1]
    video = to_denoised(inputs.video.latent, video_pred, inputs.video.timesteps)
    audio = to_denoised(inputs.audio.latent, audio_pred, inputs.audio.timesteps)
    return video[:, video_start:video_end], audio[:, audio_start:audio_end]


def model_target_pass(
    *,
    transformer: torch.nn.Module,
    inputs: ModelInputs,
    action_button_meaning_fusion: str,
    perturbations: Any = None,
    native_stage2_ar: bool = False,
) -> tuple[Tensor, Tensor]:
    if native_stage2_ar:
        from rigen_ar_model import current_block_model_pass
        return current_block_model_pass(
            transformer=transformer, inputs=inputs,
            block_index=len(inputs.ar_video_block_token_ranges) - 1,
            action_button_meaning_fusion=action_button_meaning_fusion,
            perturbations=perturbations,
        )
    video_pred, audio_pred = transformer_forward(
        transformer,
        inputs,
        action_button_meaning_fusion=action_button_meaning_fusion,
        perturbations=perturbations,
    )
    return target_x0(inputs, video_pred, audio_pred)


def prepare_inputs(
    *,
    strategy: ARSlidingRefStrategy,
    batch: dict[str, Any],
    sigma: Tensor,
    current_video: Tensor,
    current_audio: Tensor,
) -> ModelInputs:
    prepared = strategy.prepare_training_inputs(batch, FixedSigmaSampler(sigma))
    if strategy.config.name == "ar_teacher":
        from rigen_ar_model import inject_current_block
        return inject_current_block(
            prepared, block_index=len(prepared.ar_video_block_token_ranges) - 1,
            current_video=current_video, current_audio=current_audio,
        )
    return inject_target(
        prepared, current_video=current_video, current_audio=current_audio
    )


def _compact_sliding_target_prompt(
    modality: Modality, *, start: int, end: int
) -> tuple[Tensor, Tensor | None]:
    ''

    context_mask = modality.context_mask
    if context_mask is None or context_mask.ndim != 3:
        raise ValueError("Sliding-ref compact KV requires a [B,Q,K] prompt routing mask")
    if modality.context.shape[0] != 1 or context_mask.shape[0] != 1:
        raise ValueError("Sliding-ref compact KV currently requires batch size one")
    query_mask = context_mask[:, start:end].to(dtype=torch.bool)
    if query_mask.shape[1] == 0:
        raise ValueError("Sliding-ref target prompt received an empty query range")
    if not torch.equal(query_mask, query_mask[:, :1].expand_as(query_mask)):
        raise ValueError("Sliding-ref target prompt routing differs across target tokens")
    valid = query_mask[0, 0]
    if not torch.any(valid):
        raise ValueError("Sliding-ref target prompt contains no valid context tokens")
    context = modality.context[:, valid]
    context_timesteps = modality.context_timesteps
    if context_timesteps is not None:
        if context_timesteps.shape != modality.context.shape[:2]:
            raise ValueError("Sliding-ref prompt timestep/context geometry mismatch")
        context_timesteps = context_timesteps[:, valid]
    return context, context_timesteps


def _slice_sliding_target_modality(
    modality: Modality, *, start: int, end: int
) -> Modality:
    context, context_timesteps = _compact_sliding_target_prompt(
        modality, start=start, end=end
    )
    cross_timesteps = modality.cross_attention_timesteps
    if cross_timesteps is not None:
        cross_timesteps = cross_timesteps[:, start:end]
    return replace(
        modality,
        latent=modality.latent[:, start:end],
        timesteps=modality.timesteps[:, start:end],
        positions=modality.positions[:, :, start:end],
        context=context,
        context_mask=None,
        attention_mask=None,
        self_attention_block_mask=None,
        cross_attention_mask=None,
        cross_attention_timesteps=cross_timesteps,
        context_timesteps=context_timesteps,
    )


def slice_sliding_target_inputs(inputs: ModelInputs) -> ModelInputs:
    ''

    if inputs.audio is None:
        raise ValueError("Sliding-ref compact KV requires audio")
    if inputs.ar_video_block_token_ranges is None or inputs.ar_audio_block_token_ranges is None:
        raise ValueError("Sliding-ref compact KV requires block token ranges")
    video_start, video_end = inputs.ar_video_block_token_ranges[-1]
    audio_start, audio_end = inputs.ar_audio_block_token_ranges[-1]

    def slice_optional_token_tensor(value: Tensor | None) -> Tensor | None:
        if value is None:
            return None
        if value.ndim < 2 or value.shape[1] != inputs.video.latent.shape[1]:
            raise ValueError(
                "Sliding-ref per-video-token action tensor has unexpected geometry: "
                f"{tuple(value.shape)} vs {tuple(inputs.video.latent.shape)}"
            )
        return value[:, video_start:video_end]

    query_indices = inputs.action_button_query_latent_indices
    if query_indices is not None:
        if query_indices.ndim != 1 or query_indices.numel() != inputs.video.latent.shape[1]:
            raise ValueError("Sliding-ref action query indices do not match video tokens")
        query_indices = query_indices[video_start:video_end]
    return replace(
        inputs,
        video=_slice_sliding_target_modality(
            inputs.video, start=video_start, end=video_end
        ),
        audio=_slice_sliding_target_modality(
            inputs.audio, start=audio_start, end=audio_end
        ),
        action_joystick_tokens=slice_optional_token_tensor(
            inputs.action_joystick_tokens
        ),
        action_joystick_condition_mask=slice_optional_token_tensor(
            inputs.action_joystick_condition_mask
        ),
        action_button_condition_mask=slice_optional_token_tensor(
            inputs.action_button_condition_mask
        ),
        action_button_query_latent_indices=query_indices,
    )


def _select_rope_tokens(
    pe: tuple[Tensor, Tensor] | None, indices: Tensor
) -> tuple[Tensor, Tensor] | None:
    if pe is None:
        return None
    if len(pe) != 2 or pe[0].ndim != pe[1].ndim:
        raise ValueError("Block-local sliding KV received malformed RoPE tensors")
    if pe[0].ndim == 3:
        token_dimension = 1
    elif pe[0].ndim == 4:
        token_dimension = 2
    else:
        raise ValueError(
            "Block-local sliding KV requires interleaved [B,T,D] or split [B,H,T,D] RoPE, "
            f"got {tuple(pe[0].shape)}"
        )
    return (
        pe[0].index_select(token_dimension, indices),
        pe[1].index_select(token_dimension, indices),
    )


def _seed_projected_cache_from_attention(
    attention: torch.nn.Module,
    cache: ProjectedKVCache,
    args: tuple[Any, ...],
    kwargs: dict[str, Any],
    *,
    key_indices: Tensor,
) -> None:
    if cache.valid_end != 0:
        raise RuntimeError("Block-local static K/V cache was seeded more than once")
    if attention.rope_type not in (LTXRopeType.INTERLEAVED, LTXRopeType.SPLIT):
        raise RuntimeError(f"Unsupported sliding-KV RoPE type {attention.rope_type}")
    context = kwargs.get("context")
    if context is None:
        if not args or not torch.is_tensor(args[0]):
            raise RuntimeError("Unable to recover attention context for static K/V seeding")
        context = args[0]
    selected_context = context.index_select(1, key_indices)
    values = attention.to_v(selected_context)
    keys = attention.k_norm(attention.to_k(selected_context))
    key_pe = kwargs.get("k_pe") or kwargs.get("pe")
    selected_pe = _select_rope_tokens(key_pe, key_indices)
    if selected_pe is not None:
        keys = apply_rotary_emb(keys, selected_pe, attention.rope_type)
    cache.update(keys, values, start=0)


def seed_sliding_block_cache(
    *,
    transformer: torch.nn.Module,
    inputs: ModelInputs,
    cache: AVKVCacheBank,
    reference_present: bool,
    action_button_meaning_fusion: str,
) -> tuple[tuple[Tensor, Tensor], dict[str, int]]:
    ''

    if inputs.audio is None:
        raise ValueError("Sliding-ref cache seeding requires audio")
    if inputs.ar_video_block_token_ranges is None or inputs.ar_audio_block_token_ranges is None:
        raise ValueError("Sliding-ref cache seeding requires block token ranges")
    video_target_start, video_target_end = inputs.ar_video_block_token_ranges[-1]
    audio_target_start, _audio_target_end = inputs.ar_audio_block_token_ranges[-1]
    video_total = int(inputs.video.latent.shape[1])
    reference_start = video_target_end
    if reference_start > video_total:
        raise ValueError("Sliding-ref reference suffix starts beyond the video sequence")
    device = inputs.video.latent.device
    video_prefix = torch.arange(video_target_start, device=device, dtype=torch.long)
    if reference_present:
        reference = torch.arange(reference_start, video_total, device=device, dtype=torch.long)
        video_self_indices = torch.cat((video_prefix, reference))
    else:
        video_self_indices = video_prefix
    audio_prefix_indices = torch.arange(audio_target_start, device=device, dtype=torch.long)

    handles: list[Any] = []
    seed_calls = {"video_self": 0, "audio_self": 0, "audio_to_video": 0, "video_to_audio": 0}

    def install(
        module: torch.nn.Module,
        projected_cache: ProjectedKVCache,
        indices: Tensor,
        route: str,
    ) -> None:
        def hook(
            attention: torch.nn.Module,
            hook_args: tuple[Any, ...],
            hook_kwargs: dict[str, Any],
        ) -> None:
            _seed_projected_cache_from_attention(
                attention,
                projected_cache,
                hook_args,
                hook_kwargs,
                key_indices=indices,
            )
            seed_calls[route] += 1

        handles.append(module.register_forward_pre_hook(hook, with_kwargs=True))

    for block, layer_cache in zip(transformer.transformer_blocks, cache.layers, strict=True):
        install(block.attn1, layer_cache.video_self, video_self_indices, "video_self")
        install(block.audio_attn1, layer_cache.audio_self, audio_prefix_indices, "audio_self")
        install(
            block.audio_to_video_attn,
            layer_cache.audio_to_video,
            audio_prefix_indices,
            "audio_to_video",
        )
        install(
            block.video_to_audio_attn,
            layer_cache.video_to_audio,
            video_prefix,
            "video_to_audio",
        )
    try:
        output = model_target_pass(
            transformer=transformer,
            inputs=inputs,
            action_button_meaning_fusion=action_button_meaning_fusion,
        )
    finally:
        for handle in handles:
            handle.remove()
    expected = len(transformer.transformer_blocks)
    if any(count != expected for count in seed_calls.values()):
        raise RuntimeError(
            f"Incomplete block-local K/V seed routes: {seed_calls}, expected={expected} each"
        )
    return output, seed_calls


def relative_l2(actual: Tensor, expected: Tensor) -> float:
    numerator = torch.linalg.vector_norm((actual.float() - expected.float()).flatten())
    denominator = torch.linalg.vector_norm(expected.float().flatten()).clamp_min(1e-12)
    return float((numerator / denominator).item())


def build_long_duel_prompt_variants(
    base_prompt: str, *, weapon_name: str
) -> dict[str, str]:
    ''

    identity_header = "[ACTIVE OPPONENT IDENTITY]"
    if identity_header not in base_prompt:
        raise ValueError(
            "VLM sliding duel requires the new [ACTIVE OPPONENT IDENTITY] prompt contract"
        )
    stable_prefix = base_prompt.split(identity_header, 1)[0].rstrip()

    def render(identity: str, interaction: str) -> str:
        return (
            f"{stable_prefix}\n{identity_header}\n{identity}\n"
            "[CURRENT OPPONENT MOTION, VISIBILITY, AND INTERACTION]\n"
            f"{interaction}"
        )

    active_identity = (
        "The active opponent has the appearance shown in the current reference image."
    )
    previous_identity = (
        "The previous opponent had the appearance shown in its reference image."
    )
    no_identity = "No opponent is active during this block."

    variants: dict[str, str] = {}
    for direction in ("left", "right"):
        movement = (
            f"The opponent moves toward the player's {direction} while approaching."
        )
        variants[f"active_{direction}"] = render(active_identity, movement)
        variants[f"hit_alive_{direction}"] = render(
            active_identity,
            f"{movement} The player fires the {weapon_name} while moving, hits the "
            "opponent, and the opponent remains alive.",
        )
        variants[f"killed_{direction}"] = render(
            active_identity,
            f"{movement} The player fires the {weapon_name} while moving. "
            "The opponent is killed while still moving during this block, falls, "
            "and remains dead through the end of the block.",
        )
        variants[f"reentry_{direction}"] = render(
            active_identity,
            (
                "The same opponent reappears on the left and moves toward the player's right."
                if direction == "left"
                else "The same opponent reappears on the right and moves toward the player's left."
            ),
        )
    variants["active_offscreen"] = render(
        active_identity,
        "The active opponent remains temporarily outside the player's view during this block.",
    )
    variants["active_reacquire"] = render(
        active_identity,
        "The same living opponent continues moving through the scene and can come back "
        "into view as the player searches. Preserve the opponent's identity and health; "
        "this is not a death or respawn. Do not keep the opponent deliberately offscreen.",
    )
    variants["corpse"] = render(
        active_identity,
        "The opponent starts this block dead and remains a motionless corpse throughout the block.",
    )
    variants["despawn"] = render(
        previous_identity,
        "The previous opponent's motionless corpse disappears at the start of this block. "
        "No opponent remains visible.",
    )
    variants["no_enemy"] = render(
        no_identity,
        "No enemy is visible during this block.",
    )
    return variants


def infer_warm_duel_rule_state(prompts: list[str]) -> dict[str, Any]:
    ''

    hp = 100
    events: list[dict[str, Any]] = []
    for local_index, prompt in enumerate(prompts):
        interaction = prompt.split(
            "[CURRENT OPPONENT MOTION, VISIBILITY, AND INTERACTION]\n", 1
        )[-1]
        lower = interaction.lower()
        if "new opponent appears" in lower or "same opponent reappears" in lower:
            hp = 100
            events.append({"warm_local_block": local_index, "event": "entry", "hp": hp})
        if "hits the opponent, and the opponent remains alive" in lower:
            hp = max(0, hp - 50)
            events.append(
                {"warm_local_block": local_index, "event": "verified_hit_alive", "hp": hp}
            )
        if "opponent is killed" in lower:
            hp = 0
            events.append({"warm_local_block": local_index, "event": "killed", "hp": hp})
    if hp <= 0:
        raise ValueError(
            "VLM duel warm history ends with a dead opponent; select an active target block"
        )
    return {"enemy_hp": hp, "events": events}


def tensor_frame_to_image(video: Tensor, frame_index: int) -> Image.Image:
    if video.ndim != 4 or video.shape[0] != 3:
        raise ValueError(f"Expected decoded [3,F,H,W] video, got {tuple(video.shape)}")
    if not 0 <= frame_index < video.shape[1]:
        raise IndexError(f"Frame {frame_index} outside decoded length {video.shape[1]}")
    array = (
        video[:, frame_index]
        .detach()
        .float()
        .clamp(0, 1)
        .permute(1, 2, 0)
        .mul(255)
        .round()
        .to(torch.uint8)
        .cpu()
        .numpy()
    )
    return Image.fromarray(array, mode="RGB")


def pixels_frame_to_image(video: Tensor, frame_index: int) -> Image.Image:
    ''

    if video.ndim != 4 or video.shape[1] != 3:
        raise ValueError(f"Expected loader pixels [F,3,H,W], got {tuple(video.shape)}")
    if not 0 <= frame_index < video.shape[0]:
        raise IndexError(f"Frame {frame_index} outside loader pixels {video.shape[0]}")
    array = (
        video[frame_index]
        .detach()
        .float()
        .clamp(0, 1)
        .permute(1, 2, 0)
        .mul(255)
        .round()
        .to(torch.uint8)
        .cpu()
        .numpy()
    )
    return Image.fromarray(array, mode="RGB")


