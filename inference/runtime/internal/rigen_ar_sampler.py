def read_manifest_row(path: Path, index: int) -> dict[str, Any]:
    if index < 0:
        raise ValueError("--manifest-index must be non-negative")
    with path.open("r", encoding="utf-8") as handle:
        for line_index, line in enumerate(handle):
            if line_index == index:
                row = json.loads(line)
                if not isinstance(row, dict):
                    raise TypeError(f"Manifest row {index} is not an object")
                return row
    raise IndexError(f"Manifest index {index} is outside {path}")


def resolve_data_path(value: Any, *, manifest: Path, data_root: Path) -> Path:
    path = Path(str(value)).expanduser()
    candidates = (
        path,
        manifest.parent / path,
        data_root / path,
    )
    for candidate in candidates:
        if candidate.exists():
            return candidate.resolve()
    raise FileNotFoundError(
        f"Cannot resolve {value!r}; tried "
        + ", ".join(str(item) for item in candidates)
    )


def validate_row_and_geometry(
    row: dict[str, Any],
    *,
    first_target: int,
    rollout_blocks: int,
    allow_empty_history_bootstrap: bool = False,
) -> None:
    if rollout_blocks <= 0:
        raise ValueError("--rollout-blocks must be positive")
    schedule = row.get("prompt_schedule")
    active_refs = row.get("active_ref_schedule")
    bank = row.get("reference_bank")
    if not isinstance(schedule, list) or not all(
        isinstance(item, str) for item in schedule
    ):
        raise ValueError("Selected row has no string prompt_schedule")
    if not isinstance(active_refs, list) or len(active_refs) != len(schedule):
        raise ValueError("Selected row has no aligned active_ref_schedule")
    if not isinstance(bank, list) or not bank:
        raise ValueError("Selected row has no reference_bank")
    if first_target < 4 and not allow_empty_history_bootstrap:
        raise ValueError("Exact sliding-ref rollout requires first_target_block >= 4")
    if first_target + rollout_blocks > len(schedule):
        raise ValueError(
            f"Requested blocks [{first_target}, {first_target + rollout_blocks}) exceed "
            f"the {len(schedule)}-block prompt schedule"
        )
    if row.get("action_contract_version") not in SUPPORTED_ACTION_CONTRACTS:
        raise ValueError(
            "Selected row does not use a supported Xonotic legacy6 action contract"
        )
    if row.get("reference_conditioning_ready") is not True:
        raise ValueError("Selected row is not reference_conditioning_ready")


